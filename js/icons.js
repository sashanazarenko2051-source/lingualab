let _audio = null;
function onlineWanted(langCode) {
  const s = (App.storage && App.storage.state && App.storage.state.settings) || {};
  if (s.onlineVoices === false) return false;
  if ((s.voices || {})[langCode]) return false;
  if (!/^https?:/.test(location.protocol)) return false;
  return Date.now() > _onlineDown;
}
function speakOnline(text, langCode, rate, token, fallback) {
  const s = (App.storage && App.storage.state && App.storage.state.settings) || {};
  const pct = Math.round(((rate || 1) - 1) * 100);
  const r = (pct >= 0 ? '+' : '') + Math.max(-50, Math.min(50, pct)) + '%';
  const url = `/tts?l=${langCode}&g=${s.voiceGender === 'female' ? 'female' : 'male'}&r=${encodeURIComponent(r)}&t=${encodeURIComponent(String(text).replace(/\s*\/\s*/g, ', '))}`;
  const a = new Audio(url);
  a.preload = 'auto';
  _audio = a;
  let done = false;
  const fail = (e) => {
    if (done) return; done = true;
    // Stopped on purpose (next word, next exercise): not a failure.
    if (token !== _speakToken || (e && e.name === 'AbortError')) return;
    _onlineDown = Date.now() + 30000;   // try online again in half a minute
    fallback();
  };
  a.onerror = () => fail(a.error);
  a.play().then(() => { done = true; }).catch(fail);
}

App.speak = function (text, langCode, rate) {
  if (onlineWanted(langCode)) {
    App.stopSpeech();
    const token = ++_speakToken;
    speakOnline(text, langCode, rate, token, () => speakLocal(text, langCode, rate));
    return;
  }
  speakLocal(text, langCode, rate);
};

function speakLocal(text, langCode, rate) {
  if (!('speechSynthesis' in window)) return;
  const lang = App.TTS_LANG[langCode] || 'en-US';
  const token = ++_speakToken;
  const voice = findVoice(lang);
  // An empty list means the voices haven't loaded yet: then speak by lang.
  const loaded = (_ttsVoices.length ? _ttsVoices : speechSynthesis.getVoices()).length > 0;
  if (!voice && loaded) { warnNoVoice(); return; }

  try { speechSynthesis.cancel(); } catch (e) { /* ignore */ }

  // Android Chrome silently drops speak() calls made right after cancel();
  // a short delay works around it. See crbug.com/835426.
  setTimeout(() => {
    if (token !== _speakToken) return; // a newer speak() call already took over
    try {
      // "Rád jsem pomohl / Ráda jsem pomohla": read both forms with a pause
      // instead of the slash.
      const u = new SpeechSynthesisUtterance(String(text).replace(/\s*\/\s*/g, ', '));
      u.lang = lang;
      // Slowing a voice down makes some engines choppy; neural voices are
      // clear at normal speed, the older ones get a little slower.
      u.rate = rate || (voice && /natural|neural|online|enhanced|premium/i.test(voice.name) ? 0.95 : 0.9);
      u.volume = 1;
      u.pitch = 1;
      if (voice) u.voice = voice;
      // The device may only have one voice for a language (Czech: only the
      // male Jakub). Then the other gender is imitated by the pitch.
      const vs = voiceSettings();
      const vg = voice && App.voiceGender(voice);
      if (vg && vg !== vs.gender && !vs.picked[langCode]) u.pitch = vs.gender === 'female' ? 1.5 : 0.7;
      // Chrome can garbage-collect an utterance mid-word and cut it off;
      // holding a reference until it ends prevents that.
      App._utterance = u;
      u.onend = () => { if (App._utterance === u) App._utterance = null; };
      speechSynthesis.speak(u);
    } catch (e) { /* no TTS voice available — silently skip */ }
  }, 80);
}
